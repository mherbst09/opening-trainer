// Cross-check each opening's [Opening] name and [ECO] code against the Lichess
// chess-openings dataset (CC0) and write ECO_REPORT.md. Exit code 0 always: the report
// is for review; mismatches are marked, not fatal.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { classifyLine, family, loadContent, loadLichess, moveText, normName, ROOT } from './lib';

const eco = loadLichess();
const content = loadContent();

interface Row {
  file: string;
  name: string;
  eco: string;
  ecoOk: boolean;
  nameOk: boolean;
  mainDeepest: string;
  ecosSeen: string[];
  note: string;
}

const rows: Row[] = [];
const details: string[] = [];

for (const c of content) {
  const o = c.opening;
  const classified = c.lines.map((l) => ({ line: l, cls: classifyLine(l, o.root.fen, eco) }));
  const all = classified.flatMap((x) => x.cls.matches.map((m) => m.entry));
  const ecosSeen = [...new Set(all.map((e) => e.eco))].sort();
  const main = classified[0]?.cls;
  const ecoOk = ecosSeen.includes(o.eco);
  const nameOk = all.some((e) => normName(e.name) === normName(o.name)) || all.some((e) => family(e.name) === family(o.name) && !o.name.includes(':'));
  const mainDeepest = main?.deepest ? `${main.deepest.eco} ${main.deepest.name}` : '(no named position)';
  let note = '';
  if (!ecoOk) note += `Header ECO ${o.eco} is not the code of any position in these lines. `;
  if (!nameOk) {
    const fams = [...new Set(all.map((e) => e.name.split(':')[0]))];
    note += `Header name not found in the dataset along these lines (dataset families here: ${fams.join(', ') || 'none'}). `;
  }
  rows.push({ file: c.file, name: o.name, eco: o.eco, ecoOk, nameOk, mainDeepest, ecosSeen, note: note.trim() });

  details.push(`### ${o.name} (${o.eco}) — \`${c.file}\``);
  details.push('');
  details.push('| Line | Deepest named position in the dataset | Reached after |');
  details.push('|---|---|---|');
  for (const { line, cls } of classified) {
    const d = cls.deepest ? `${cls.deepest.eco} ${cls.deepest.name}` : '—';
    const after = cls.deepestPly ? `${cls.deepestPly} plies` : '—';
    details.push(`| ${line.name} | ${d} | ${after} |`);
  }
  details.push('');
  details.push('<details><summary>Moves</summary>');
  details.push('');
  for (const { line } of classified) details.push(`- **${line.name}:** ${moveText(line, o.root.fen)}`);
  details.push('');
  details.push('</details>');
  details.push('');
}

const bad = rows.filter((r) => !r.ecoOk || !r.nameOk);
const out: string[] = [
  '# ECO / name cross-check',
  '',
  'Generated by `npm run content:check` (scripts/check-eco.ts) against the Lichess',
  '[chess-openings](https://github.com/lichess-org/chess-openings) dataset (CC0), vendored in `content/lichess/`.',
  '',
  'For each opening file, every position along every line is looked up in the dataset.',
  'The header ECO passes if it is the code of at least one of those positions; the header name passes if it',
  'equals a dataset name along the lines (or, for a name without a sub-variation, the family before the colon matches).',
  '',
  `**${rows.length} openings checked, ${bad.length} mismatch${bad.length === 1 ? '' : 'es'}.**`,
  '',
];
if (bad.length) {
  out.push('## Mismatches', '');
  for (const r of bad) out.push(`- **${r.name}** (\`${r.file}\`, ${r.eco}): ${r.note}`);
  out.push('');
}
out.push('## Summary', '', '| Opening | File | ECO | ECO ok | Name ok | Main line ends in (dataset) | ECO codes seen |', '|---|---|---|---|---|---|---|');
for (const r of rows) {
  out.push(`| ${r.name} | ${r.file} | ${r.eco} | ${r.ecoOk ? '✓' : '✗'} | ${r.nameOk ? '✓' : '✗'} | ${r.mainDeepest} | ${r.ecosSeen.join(', ')} |`);
}
out.push('', '## Per line', '', ...details);

writeFileSync(join(ROOT, 'ECO_REPORT.md'), out.join('\n'));
console.log(`ECO_REPORT.md: ${rows.length} openings, ${bad.length} mismatch(es)`);
for (const r of bad) console.log(`  ✗ ${r.file}: ${r.note}`);

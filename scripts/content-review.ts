// Write CONTENT_REVIEW.md: every built-in opening with its lines, moves and comments,
// so the theory can be reviewed by a human.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildCards } from '../src/engine/cards';
import { indexOpening } from '../src/engine/tree';
import { classifyLine, lineComments, loadContent, loadLichess, moveText, ROOT } from './lib';

const eco = loadLichess();
const content = loadContent();

const groups: { title: string; test: (c: (typeof content)[number]) => boolean }[] = [
  { title: '1.e4 as White', test: (c) => c.opening.side === 'white' && c.opening.tags.includes('e4') },
  { title: 'Against 1.e4 (Black)', test: (c) => c.opening.side === 'black' && c.opening.tags.includes('e4') },
  { title: '1.d4 as White', test: (c) => c.opening.side === 'white' && c.opening.tags.includes('d4') },
  { title: 'Against 1.d4 (Black)', test: (c) => c.opening.side === 'black' && c.opening.tags.includes('d4') },
  { title: 'Flank openings', test: (c) => c.opening.tags.includes('flank') },
];

let totalLines = 0;
let totalCards = 0;
const body: string[] = [];
const toc: string[] = [];
const used = new Set<string>();

for (const g of groups) {
  const items = content.filter((c) => !used.has(c.file) && g.test(c));
  items.forEach((c) => used.add(c.file));
  if (!items.length) continue;
  body.push(`## ${g.title}`, '');
  toc.push(`- **${g.title}:** ${items.map((c) => c.opening.name).join(' · ')}`);
  for (const c of items) {
    const o = c.opening;
    const cards = buildCards(indexOpening(o)).length;
    totalLines += c.lines.length;
    totalCards += cards;
    body.push(`### ${o.name}`, '');
    body.push(`File \`content/openings/${c.file}\` · ECO ${o.eco} · you play **${o.side}** · difficulty ${o.difficulty} · tags: ${o.tags.join(', ')} · ${c.lines.length} lines · ${cards} quiz positions`, '');
    if (c.errors.length) body.push(`> ⚠ Parse problems: ${c.errors.join('; ')}`, '');
    c.lines.forEach((line, i) => {
      const cls = classifyLine(line, o.root.fen, eco);
      const ends = cls.deepest ? ` — dataset: *${cls.deepest.eco} ${cls.deepest.name}*` : '';
      body.push(`${i + 1}. **${line.name}** (${Math.ceil(line.nodes.length / 2)} moves)${ends}`);
      body.push(`   \`${moveText(line, o.root.fen)}\``);
    });
    body.push('');
    // comments once per opening (lines share their opening moves)
    const seen = new Set<string>();
    const comments = c.lines.flatMap((l) => lineComments(l, o.root.fen)).filter((x) => {
      const k = `${x.move}|${x.text}`;
      if (seen.has(k)) return false;
      seen.add(k);
      return true;
    });
    if (comments.length) {
      body.push('<details><summary>Comments</summary>', '');
      for (const cm of comments) body.push(`- **${cm.move}** ${cm.text}`);
      body.push('', '</details>', '');
    }
  }
}

const leftovers = content.filter((c) => !used.has(c.file));
if (leftovers.length) body.push('## Other', '', ...leftovers.map((c) => `- ${c.opening.name} (\`${c.file}\`)`), '');

const out = [
  '# Content review',
  '',
  'Generated by `npm run content:review` (scripts/content-review.ts). Do not edit by hand: change the PGN files and regenerate.',
  '',
  `**${content.length} openings, ${totalLines} lines, ${totalCards} quiz positions.**`,
  '',
  'Every move is checked for legality by the test suite (`tests/content.test.ts`). Names and ECO codes are',
  'cross-checked in `ECO_REPORT.md`. Lines are mainstream theory written to be safe rather than deep:',
  'where I was not sure of the continuation I stopped the line early. Please review the moves and comments below.',
  '',
  ...toc,
  '',
  ...body,
];
writeFileSync(join(ROOT, 'CONTENT_REVIEW.md'), out.join('\n'));
console.log(`CONTENT_REVIEW.md: ${content.length} openings, ${totalLines} lines, ${totalCards} positions`);
